// Bundles the content script and its dependency-free lib modules into
// one classic script for MV3 content_scripts, which cannot load ESM.
// Usage: node scripts/bundle-content.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sources = [
  "extension/lib/eligibility.js",
  "extension/lib/settings.js",
  "extension/lib/player-dom.js",
  "extension/lib/toast.js",
  "extension/content.js",
];

function stripModule(src) {
  return src
    .split("\n")
    .filter((line) => !/^\s*import\s+.+\s+from\s+["']\.\/lib\//.test(line))
    .map((line) => line.replace(/^(\s*)export\s+(default\s+)?/, "$1"))
    .join("\n");
}

const parts = sources.map((rel) => {
  const text = readFileSync(join(root, rel), "utf8");
  return "// ---- " + rel + " ----\n" + stripModule(text);
});

const bundle = "// Generated by scripts/bundle-content.mjs. Do not edit by hand.\n" + parts.join("\n\n");

for (const line of bundle.split("\n")) {
  if (/^\s*import\s+.+\s+from\s+["']/.test(line)) {
    console.error("bundle still has an import: " + line);
    process.exit(1);
  }
  if (/^\s*export\s+(default\s+)?(class|function|const|let|var|\{)/.test(line)) {
    console.error("bundle still has an export: " + line);
    process.exit(1);
  }
}

writeFileSync(join(root, "extension", "content.bundle.js"), bundle + "\n");
console.log("wrote extension/content.bundle.js (" + bundle.length + " bytes)");

